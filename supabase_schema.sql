-- ---------- Updated-at Triggers ----------
do $$
declare
  t text;
begin
  foreach t in array array[
    'system_roles',
    'organizations',
    'user_profiles',
    'departments',
    'positions',
    'organization_members',
    'device_types',
    'attendance_devices',
    'shifts',
    'work_schedules',
    'work_schedule_details',
    'attendance_records',
    'biometric_data'
  ]
  loop
    execute format('drop trigger if exists set_updated_at_%I on public.%I', t, t);
    execute format(
      'create trigger set_updated_at_%I before update on public.%I for each row execute function public.set_updated_at()',
      t, t
    );
  end loop;
end $$;

-- ---------- Auth Trigger: Auto-create User Profile & Default Membership ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_full_name text;
  v_first_name text;
  v_last_name text;
begin
  v_full_name := trim(coalesce(
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'name',
    split_part(new.email, '@', 1),
    ''
  ));
  v_first_name := coalesce(nullif(split_part(v_full_name, ' ', 1), ''), '');
  v_last_name := coalesce(
    nullif(trim(substring(v_full_name from length(split_part(v_full_name, ' ', 1)) + 1)), ''),
    ''
  );

  insert into public.user_profiles (
    id, email, first_name, last_name, display_name, jenis_kelamin, is_active
  )
  values (
    new.id,
    new.email,
    v_first_name,
    v_last_name,
    nullif(v_full_name, ''),
    'male',
    true
  )
  on conflict (id) do nothing;

  -- Otomatis masukkan user baru ke organisasi utama (id = 1 / ORG001) sebagai User (role_id = 2)
  insert into public.organization_members (organization_id, user_id, role_id, is_active)
  select o.id, new.id, 2, true
  from public.organizations o
  where o.id = 1
  on conflict (organization_id, user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

