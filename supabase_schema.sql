-- ---------- Row Level Security (RLS) ----------
do $$
declare
  t text;
begin
  foreach t in array array[
    'system_roles',
    'organizations',
    'user_profiles',
    'departments',
    'positions',
    'organization_members',
    'device_types',
    'attendance_devices',
    'shifts',
    'work_schedules',
    'work_schedule_details',
    'attendance_records',
    'attendance_logs',
    'biometric_data',
    'audit_logs'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "authenticated all access" on public.%I', t);
    execute format(
      'create policy "authenticated all access" on public.%I for all to authenticated using (true) with check (true)',
      t
    );
  end loop;
end $$;

-- Storage RLS Policies
drop policy if exists "public storage read" on storage.objects;
create policy "public storage read" on storage.objects
for select to anon, authenticated
using (bucket_id in ('profile-photos', 'photo-attendance'));

drop policy if exists "authenticated storage read" on storage.objects;
create policy "authenticated storage read" on storage.objects
for select to authenticated
using (bucket_id in ('profile-photos', 'photo-attendance', 'face-templates'));

drop policy if exists "authenticated storage insert" on storage.objects;
create policy "authenticated storage insert" on storage.objects
for insert to authenticated
with check (bucket_id in ('profile-photos', 'photo-attendance', 'face-templates'));

drop policy if exists "authenticated storage update" on storage.objects;
create policy "authenticated storage update" on storage.objects
for update to authenticated
using (bucket_id in ('profile-photos', 'photo-attendance', 'face-templates'))
with check (bucket_id in ('profile-photos', 'photo-attendance', 'face-templates'));

drop policy if exists "authenticated storage delete" on storage.objects;
create policy "authenticated storage delete" on storage.objects
for delete to authenticated
using (bucket_id in ('profile-photos', 'photo-attendance', 'face-templates'));

