-- ---------- Helper untuk Membuat Akun Login Terpisah per Role ----------
create or replace function public.upsert_role_account(
  p_email text,
  p_password text,
  p_first_name text,
  p_last_name text,
  p_display_name text,
  p_employee_id text,
  p_role_id int
)
returns uuid
language plpgsql
security definer
set search_path = public, auth, extensions
as $$
declare
  v_user_id uuid;
begin
  select id into v_user_id
  from auth.users
  where email = p_email
  limit 1;

  if v_user_id is null then
    v_user_id := gen_random_uuid();

    insert into auth.users (
      instance_id, id, aud, role, email, encrypted_password,
      email_confirmed_at, confirmation_token, recovery_token,
      email_change_token_new, email_change,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at
    )
    values (
      '00000000-0000-0000-0000-000000000000',
      v_user_id,
      'authenticated',
      'authenticated',
      p_email,
      crypt(p_password, gen_salt('bf')),
      now(),
      '', '', '', '',
      '{"provider":"email","providers":["email"]}'::jsonb,
      jsonb_build_object('full_name', p_display_name, 'name', p_display_name),
      now(),
      now()
    );

    insert into auth.identities (
      id, user_id, provider_id, identity_data, provider,
      last_sign_in_at, created_at, updated_at
    )
    values (
      gen_random_uuid(),
      v_user_id,
      v_user_id::text,
      jsonb_build_object(
        'sub', v_user_id::text,
        'email', p_email,
        'email_verified', true,
        'phone_verified', false
      ),
      'email',
      now(),
      now(),
      now()
    );
  else
    update auth.users
    set encrypted_password = crypt(p_password, gen_salt('bf')),
        email_confirmed_at = coalesce(email_confirmed_at, now()),
        raw_user_meta_data = jsonb_build_object('full_name', p_display_name, 'name', p_display_name),
        updated_at = now()
    where id = v_user_id;
  end if;

  insert into public.user_profiles (
    id, email, first_name, last_name, display_name, jenis_kelamin, is_active
  )
  values (
    v_user_id, p_email, p_first_name, p_last_name, p_display_name, 'male', true
  )
  on conflict (id) do update set
    email = excluded.email,
    first_name = excluded.first_name,
    last_name = excluded.last_name,
    display_name = excluded.display_name,
    is_active = true;

  insert into public.organization_members (
    organization_id, user_id, employee_id, role_id, is_active
  )
  values (
    1, v_user_id, p_employee_id, p_role_id, true
  )
  on conflict (organization_id, user_id) do update set
    employee_id = excluded.employee_id,
    role_id = excluded.role_id,
    is_active = true;

  return v_user_id;
end;
$$;

